package com.example.examprep.auth;

import android.content.Intent;
import android.os.Bundle;
import android.util.Log;
import android.view.View;
import android.widget.ProgressBar;
import android.widget.Toast;

import androidx.annotation.NonNull;
import androidx.appcompat.app.AppCompatActivity;
import androidx.core.content.ContextCompat;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.NoCredentialException;

import com.example.examprep.R;
import com.example.examprep.ui.MainActivity;
import com.google.android.gms.tasks.Task;
import com.google.android.libraries.identity.googleid.GetGoogleIdOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;
import com.google.android.material.button.MaterialButton;
import com.google.firebase.auth.AuthCredential;
import com.google.firebase.auth.FirebaseAuth;
import com.google.firebase.auth.GoogleAuthProvider;

/** Launcher screen: welcome page + "Continue with Google". Skips itself if already signed in. */
public class WelcomeActivity extends AppCompatActivity {

    private static final String TAG = "WelcomeActivity";

    private MaterialButton btnGoogle;
    private ProgressBar progress;
    private CredentialManager credentialManager;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);

        // Already logged in -> go straight to the app, no flash of the welcome screen.
        if (AuthManager.isLoggedIn()) {
            openMain();
            return;
        }

        setContentView(R.layout.activity_welcome);
        credentialManager = CredentialManager.create(this);
        btnGoogle = findViewById(R.id.btn_google_sign_in);
        progress = findViewById(R.id.progress_sign_in);
        btnGoogle.setOnClickListener(v -> startGoogleSignIn());
    }

    private void startGoogleSignIn() {
        setLoading(true);

        // default_web_client_id is generated by the google-services plugin from google-services.json
        GetGoogleIdOption googleIdOption = new GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(getString(R.string.default_web_client_id))
                .build();

        GetCredentialRequest request = new GetCredentialRequest.Builder()
                .addCredentialOption(googleIdOption)
                .build();

        credentialManager.getCredentialAsync(
                this, request, null, ContextCompat.getMainExecutor(this),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse result) {
                        handleCredential(result.getCredential());
                    }

                    @Override
                    public void onError(@NonNull GetCredentialException e) {
                        setLoading(false);
                        if (e instanceof GetCredentialCancellationException) return; // user closed the sheet
                        Log.e(TAG, "Credential error", e);
                        if (e instanceof NoCredentialException) {
                            toast(getString(R.string.login_error_no_account));
                        } else {
                            toast(getString(R.string.login_error_generic));
                        }
                    }
                });
    }

    private void handleCredential(Credential credential) {
        if (credential instanceof CustomCredential
                && GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL.equals(credential.getType())) {
            GoogleIdTokenCredential googleCred =
                    GoogleIdTokenCredential.createFrom(((CustomCredential) credential).getData());
            firebaseAuthWithGoogle(googleCred.getIdToken());
        } else {
            setLoading(false);
            toast(getString(R.string.login_error_generic));
        }
    }

    private void firebaseAuthWithGoogle(String idToken) {
        AuthCredential firebaseCred = GoogleAuthProvider.getCredential(idToken, null);
        Task<?> task = FirebaseAuth.getInstance().signInWithCredential(firebaseCred);
        task.addOnCompleteListener(this, t -> {
            if (t.isSuccessful()) {
                openMain();
            } else {
                setLoading(false);
                Log.e(TAG, "Firebase sign-in failed", t.getException());
                toast(getString(R.string.login_error_generic));
            }
        });
    }

    private void openMain() {
        Intent intent = new Intent(this, MainActivity.class);
        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TASK);
        startActivity(intent);
        finish();
    }

    private void setLoading(boolean loading) {
        btnGoogle.setEnabled(!loading);
        progress.setVisibility(loading ? View.VISIBLE : View.GONE);
    }

    private void toast(String msg) {
        Toast.makeText(this, msg, Toast.LENGTH_LONG).show();
    }
}
